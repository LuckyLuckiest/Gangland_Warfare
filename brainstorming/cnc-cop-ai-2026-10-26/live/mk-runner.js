#!/usr/bin/env node
// mk-runner.js - writes live/run-copai.js: an additive copy of harness/run-cnc020.js (same steps, same outputs) that
//   1. resolves mineflayer/vec3/prismarine-chat and slots.js from the harness folder (so it runs from live/),
//   2. stamps every chat.txt line with the local wall clock [HH:MM:SS.mmm] (server.log uses the same clock),
//   3. also records boss bars ([bossbar+]/[bossbar]/[bossbar-], deduped by title) and titles into chat.txt
//      (the wanted HUD's evasion countdown lives in the boss bar, which run.js does not capture).
// Re-run after any harness/run-cnc020.js change: node mk-runner.js
'use strict';
const fs = require('fs');
const path = require('path');
const H = 'E:/Programming/java/wt/_programme/harness';
let src = fs.readFileSync(path.join(H, 'run-cnc020.js'), 'utf8');
const rep = (from, to) => {
  if (!src.includes(from)) throw new Error('patch anchor missing: ' + from.slice(0, 60));
  src = src.replace(from, to);
};
rep("'use strict';", "'use strict';\nmodule.paths.unshift('" + H + "/node_modules');");
rep("require('./slots')", "require('" + H + "/slots')");
rep('const chat = [];         // {bot, pos, text}',
  'const chat = [];         // {t, bot, pos, text}\n' +
  "const ts = () => { const d = new Date(), p = (n, w = 2) => String(n).padStart(w, '0'); return `${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}.${p(d.getMilliseconds(), 3)}`; };\n" +
  '{ const push0 = chat.push.bind(chat); chat.push = (...a) => push0(...a.map(c => { c.t = c.t || ts(); return c; })); }\n' +
  'const lastBar = {};');
rep("    bot.on('message', (m, pos) => chat.push({ bot: name, pos, text: strip(m.toString()) }));",
  "    bot.on('message', (m, pos) => chat.push({ bot: name, pos, text: strip(m.toString()) }));\n" +
  "    const barText = b => { try { return strip(String(b.title)); } catch { return '?'; } };\n" +
  "    bot.on('bossBarCreated', b => { lastBar[name + ':' + b.entityUUID] = barText(b); chat.push({ bot: name, pos: 'bossbar', text: '[bossbar+] ' + lastBar[name + ':' + b.entityUUID] }); });\n" +
  "    bot.on('bossBarUpdated', b => { const tx = barText(b); if (lastBar[name + ':' + b.entityUUID] !== tx) { lastBar[name + ':' + b.entityUUID] = tx; chat.push({ bot: name, pos: 'bossbar', text: '[bossbar] ' + tx }); } });\n" +
  "    bot.on('bossBarDeleted', b => { lastBar[name + ':' + b.entityUUID] = null; chat.push({ bot: name, pos: 'bossbar', text: '[bossbar-] ' + barText(b) }); });\n" +
  "    const titleText = t => { try { const o = typeof t === 'string' ? JSON.parse(t) : t; const nbt = require('prismarine-nbt'); const tagged = x => x && typeof x === 'object' && 'type' in x && 'value' in x; const v = tagged(o) ? nbt.simplify(o) : o && typeof o === 'object' && Object.values(o).every(tagged) ? nbt.simplify({ type: 'compound', value: o }) : o; return strip(new ChatMessage(v).toString()); } catch { return plain(t); } };\n" +
  "    bot.on('title', (t, type) => chat.push({ bot: name, pos: 'title', text: '[' + (type || 'title') + '] ' + titleText(t) }));");
rep("  if ('quit' in st)", "  if ('sneak' in st) { botOf(st).setControlState('sneak', !!st.sneak); await sleep(200); return 'sneak ' + st.sneak; }\n  if ('quit' in st)");
// ACC9 poll step {poll: <console cmd>, until: <log regex>, every: ms, timeout: ms}: re-issue the command until a line
// logged after one of its issues matches (acc-spawn-view waits for the last squad to be gone before SV-S / SV-N)
rep("  if ('quit' in st)", "  if ('poll' in st) {\n" +
  "    const re = new RegExp(st.until, 'i'), end = Date.now() + (st.timeout ?? 60000);\n" +
  "    for (let n = 1; ; n++) {\n" +
  "      const from = log.length; consoleCmd(st.poll);\n" +
  "      if (await waitLog(re, st.every ?? 3000, from) >= 0) return `${st.poll} -> /${st.until}/ after ${n} tries`;\n" +
  "      if (exited || Date.now() > end) throw new Error(`poll: no log line matching /${st.until}/ after ${n} tries`);\n" +
  "    }\n" +
  "  }\n  if ('quit' in st)");
rep("chat.map(c => `[${c.bot}", "chat.map(c => `[${c.t}][${c.bot}");
src = src.replace(/^\/\/ GENERATED by .*$/m,
  '// GENERATED by brainstorming/cnc-cop-ai-2026-10-26/live/mk-runner.js from harness/run-cnc020.js. Do not hand-edit.');
fs.writeFileSync(path.join(__dirname, 'run-copai.js'), src);
console.log('wrote run-copai.js (' + src.length + ' bytes)');
